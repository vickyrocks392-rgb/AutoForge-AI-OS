def test_4_policy_scoring_evaluates_quality_and_reliability(test_infra):
    """Criterion 5: LocalFirstRoutingPolicy scores quality tiers and respects reliability."""
    policy = LocalFirstRoutingPolicy()
    models = test_infra["registry"].query_models(ModelQuery())
    assert len(models) >= 2

    # High quality request should boost high quality tier models
    req_high_q = RoutingRequest(
        required_capabilities=frozenset({"reasoning"}),
        quality_priority=5,
    )
    scores_high_q = {m.model_id: policy.score(m, None, req_high_q) for m in models}

    # Low quality priority
    req_low_q = RoutingRequest(
        required_capabilities=frozenset({"reasoning"}),
        quality_priority=1,
    )
    scores_low_q = {m.model_id: policy.score(m, None, req_low_q) for m in models}

    # Scores should be different based on quality_priority
    assert scores_high_q != scores_low_q


@pytest.mark.asyncio
async def test_5_capacity_aware_router_manages_concurrency_slots(test_infra):
    """Criterion 6: CapacityAwareRouter and ModelCapacityManager participate in slot acquisition and release."""
    cap_router = test_infra["capacity_router"]
    cap_mgr = test_infra["capacity_mgr"]

    model_id = "ornith-9b"
    provider_id = "local-m1"
    assert await cap_mgr.is_available(model_id, provider_id) is True
    assert cap_mgr._active_runs.get(model_id, 0) == 0

    # Acquire slot
    ok = await cap_mgr.acquire_slot(model_id, provider_id, timeout_seconds=1.0)
    assert ok is True
    assert cap_mgr._active_runs.get(model_id, 0) == 1

    # Release slot
    await cap_mgr.release_slot(model_id)
    assert cap_mgr._active_runs.get(model_id, 0) == 0


