@pytest.mark.asyncio
async def test_11_legacy_modernization_g3_llm_canonical_wiring(test_infra):
    """Criterion 12, 13, 14: G3LLMIntegration uses canonical AI infrastructure and preserves offline fallback."""
    ai_adapter = AIInfrastructureAdapter(
        model_executor=test_infra["executor_registry"],
        capacity_router=test_infra["capacity_router"],
        allow_deterministic_fallback=False,
    )

    # 1. With canonical AI adapter connected
    g3 = G3LLMIntegration(ai_adapter=ai_adapter, force_offline=False)
    assert g3.is_available is True

    res = await g3.interpret_business_rule(
        rt="COMPUTE TAX = AMOUNT * 0.05",
        sc="IF AMT > 100",
        er=["test-evidence"],
    )
    assert res.is_reliable() is True
    assert "Genuine model reasoning" in res.conclusion
    assert res.model in ("ornith-9b", "qwen2.5-coder-7b", "qwen2.5-coder-3b")

    # 2. With force_offline=True (exact 18-G default behavior)
    g3_offline = G3LLMIntegration(ai_adapter=ai_adapter, force_offline=True)
    assert g3_offline.is_available is False
    res_offline = await g3_offline.interpret_business_rule("rt", "sc", [])
    assert res_offline.conclusion == "LLM_UNAVAILABLE"
    assert res_offline.is_fabricated is True
