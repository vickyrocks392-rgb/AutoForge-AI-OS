def test_1_all_23_workers_contract_and_classification():
    """Criterion 1 & 2: Every AI worker declares valid requirements, deterministic workers remain deterministic."""
    assert len(WORKER_CLASSES) == 23

    deterministic_types = {"legacy_systems_research_engineer", "business_rules_analyst"}
    ai_required_count = 0
    deterministic_count = 0

    for cls in WORKER_CLASSES:
        exp = cls.expertise
        profile = exp.model_profile
        assert profile is not None
        assert profile.worker_type == cls.specialized_type

        if cls.specialized_type in deterministic_types:
            deterministic_count += 1
            # Deterministic workers do not require coding or heavy model routing
            assert len(profile.required_capabilities) >= 0
        else:
            ai_required_count += 1
            # AI-required workers must declare capabilities and context window
            assert len(profile.required_capabilities) > 0
            assert profile.min_context_window_tokens > 0
            assert profile.quality_priority in (1, 2, 3, 4, 5)

    assert ai_required_count == 21
    assert deterministic_count == 2


def test_2_all_23_loops_are_registered_and_specialized():
    """Criterion 1 & 2: Every worker maps to an explicit specialized loop in _LOOP_CLASSES."""
    assert len(_LOOP_CLASSES) == 23

    for cls in WORKER_CLASSES:
        loop_type = cls.expertise.default_loop_type
        assert loop_type in _LOOP_CLASSES, f"Missing loop class for {cls.specialized_type} ({loop_type})"
        loop_cls = get_loop_class(loop_type)
        assert loop_cls.__name__ != "EngineeringLoop" or loop_type in ("backend", "frontend")


