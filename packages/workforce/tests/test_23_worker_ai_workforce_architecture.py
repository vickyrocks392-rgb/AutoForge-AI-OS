class MockTestProviderAdapter(BaseProviderAdapter):
    """Provider adapter for tracing execution without requiring live external daemons."""

    def __init__(self, provider_id: str = "mock-provider", base_url: str = "http://127.0.0.1:11434"):
        super().__init__(provider_id=provider_id)
        self.base_url = base_url
        self.invocations: list[tuple[ExecutionRequest, ExecutionTarget]] = []
        self.should_fail = False

    async def execute(self, request: ExecutionRequest, target: ExecutionTarget) -> dict[str, Any]:
        self.invocations.append((request, target))
        if self.should_fail:
            raise RuntimeError("Simulated inference backend failure")
        return {
            "content": f"Genuine model reasoning generated by {target.model_id} on {target.provider_id}. This is a substantive response exceeding minimum length requirements.",
            "plan": f"Genuine model reasoning generated by {target.model_id} on {target.provider_id}. Comprehensive plan details.",
        }

    async def check_health(self) -> bool:
        return True


