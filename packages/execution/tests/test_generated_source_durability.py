@pytest.mark.asyncio
async def test_distinct_artifacts_with_same_name_do_not_overwrite(tmp_path: Path):
    """DEF-18L-06: two different logical artifacts must not share one file.

    Two genuinely different artifacts can carry the same ``artifact_name``
    (two QALoop runs both emit "qa_test_strategy.md"). They mint different
    catalog identities, so publishing both to one path silently replaced the
    first artifact's bytes while its record stayed COMMITTED with a
    now-wrong content hash.
    """
    import hashlib

    from autoforge_execution.models import ArtifactProvenance

    catalog, store = _durable(tmp_path)
    pipeline = ArtifactPipeline(durable_catalog=catalog, physical_store=store)
    wf_id = uuid.uuid4()

    def prov(task: str):
        return ArtifactProvenance(
            task_id=task, worker_id="w1", workflow_id=wf_id, iteration=1
        )

    a = pipeline.record_artifact(
        name="qa_test_strategy.md", artifact_type=ArtifactType.SUMMARY,
        content="STRATEGY A", provenance=prov("task-a"),
    )
    b = pipeline.record_artifact(
        name="qa_test_strategy.md", artifact_type=ArtifactType.SUMMARY,
        content="STRATEGY B", provenance=prov("task-b"),
    )

    assert a.artifact_id != b.artifact_id
    assert a.path != b.path, "distinct artifacts must not share one physical file"

    # Both COMMITTED artifacts must still hash-verify against their own bytes.
    for rec, text in ((a, "STRATEGY A"), (b, "STRATEGY B")):
        on_disk = Path(rec.path).read_text(encoding="utf-8")
        assert on_disk == text
        assert hashlib.sha256(on_disk.encode("utf-8")).hexdigest() == rec.checksum
