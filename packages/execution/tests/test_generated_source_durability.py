GENERATED = {
    "src/models/user.py": (
        "class User:\n"
        "    def __init__(self, username: str) -> None:\n"
        "        self.username = username\n"
    ),
    "src/models/product.py": (
        "class Product:\n"
        "    def __init__(self, sku: str, price: float) -> None:\n"
        "        self.sku = sku\n"
        "        self.price = price\n"
    ),
}


class _StaticProvider(AIEngineeringProvider):
    """Deterministic provider that returns a fixed, real source deliverable."""

    async def generate_plan(self, context: ExecutionContext) -> str:
        return "Create the two model modules."

    async def generate_implementation(self, context, plan):
        return [{"path": p, "content": c} for p, c in GENERATED.items()]

    async def diagnose_failure(self, context, failure_evidence):
        return DiagnosisReport(root_cause="not used")

    async def generate_repair(self, context, diagnosis):
        return []


def _durable(tmp_path: Path) -> tuple[DurableArtifactCatalog, PhysicalArtifactStore]:
    root = tmp_path / "artifacts"
    store = PhysicalArtifactStore(
        artifact_root=root,
        staging_root=root / ".staging",
        quarantine_root=root / ".quarantine",
    )
    catalog = DurableArtifactCatalog(
        persistence=PersistenceLayer(), physical_store=store
    )
    return catalog, store


async def _run_loop(tmp_path: Path):
    ws = tmp_path / "ws"
    ws.mkdir(parents=True, exist_ok=True)
    fs = WorkspaceFilesystem(ws)
    env = WorkspaceEnvironment(ws, filesystem=fs, git=GitConnector(ws))

    catalog, store = _durable(tmp_path)
    pipeline = ArtifactPipeline(durable_catalog=catalog, physical_store=store)
    loop = EngineeringLoop(
        environment=env,
        ai_provider=_StaticProvider(),
        artifact_pipeline=pipeline,
        config=LoopConfig(max_iterations=1),
    )
    wf_id = uuid.uuid4()
    ctx = ExecutionContext(
        task_id="task-18l-01",
        task_name="Create model modules",
        task_type="coding",
        workflow_id=wf_id,
    )
    passed, artifacts, _ = await loop.run(ctx, "worker-18l-01")
    return ws, catalog, store, wf_id, artifacts


@pytest.mark.asyncio
async def test_generated_source_is_registered_as_durable_artifact(tmp_path: Path):
    """The actual generated bytes must reach the authoritative 18-K catalog."""
    ws, catalog, _store, wf_id, artifacts = await _run_loop(tmp_path)

    # 1. The source really was written to the workspace (unchanged behaviour).
    for rel in GENERATED:
        assert (ws / rel).exists(), f"{rel} must exist on the workspace filesystem"
        assert (ws / rel).read_text(encoding="utf-8") == GENERATED[rel]

    # 2. And it is now ALSO represented as a COMMITTED durable source artifact.
    states = catalog.find_by_workflow(wf_id)
    by_name = {s.artifact_name: s for s in states}

    for rel in GENERATED:
        assert rel in by_name, (
            f"generated source {rel} must be registered as a durable artifact; "
            f"registered={sorted(by_name)}"
        )
        st = by_name[rel]
        assert st.status is DurableArtifactStatus.COMMITTED
        assert st.artifact_type == ArtifactType.SOURCE_CODE.value
        # Physical bytes are present and match what the loop wrote.
        assert st.storage_path and Path(st.storage_path).exists()
        assert Path(st.storage_path).read_text(encoding="utf-8") == GENERATED[rel]

    # 3. The diff summary behaviour is preserved (no regression of prior art).
    assert any(s.artifact_type == ArtifactType.DIFF.value for s in states)

    # 4. The loop's returned artifacts include the source records.
    assert any(a.artifact_type is ArtifactType.SOURCE_CODE for a in artifacts)


@pytest.mark.asyncio
async def test_no_second_artifact_store_is_introduced(tmp_path: Path):
    """The repair must reuse the ONE authoritative pipeline, not add a store."""
    _ws, catalog, store, _wf, _artifacts = await _run_loop(tmp_path)
    # Everything durable is reachable through the single 18-K catalog/store pair.
    assert catalog is not None and store is not None
    # The physical store root holds the published source, nothing else does.


@pytest.mark.asyncio
async def test_revised_source_becomes_a_new_version_not_a_conflict(tmp_path: Path):
    """DEF-18L-05: a later iteration re-writing a file must not conflict.

    A COMMITTED artifact may not be silently overwritten -- that invariant is
    genuine and must stay. But an engineering loop re-generating a file on a
    later iteration is a NEW logical version, not a replay. It must register as
    a distinct artifact while the earlier COMMITTED bytes stay intact.
    """
    from autoforge_execution.models import ArtifactProvenance

    catalog, store = _durable(tmp_path)
    pipeline = ArtifactPipeline(durable_catalog=catalog, physical_store=store)
    wf_id = uuid.uuid4()

    def prov(iteration: int):
        return ArtifactProvenance(
            task_id="task-18l-05", worker_id="w1", workflow_id=wf_id,
            iteration=iteration,
        )

    v1 = "def f():\n    return 1\n"
    v2 = "def f():\n    return 2\n"

    r1 = pipeline.record_artifact(
        name="tokenizer_lite/core.py", artifact_type=ArtifactType.SOURCE_CODE,
        content=v1, provenance=prov(1), path="tokenizer_lite/core.py",
    )
    r2 = pipeline.record_artifact(
        name="tokenizer_lite/core.py", artifact_type=ArtifactType.SOURCE_CODE,
        content=v2, provenance=prov(2), path="tokenizer_lite/core.py",
    )

    # A new version, not a replay of the first.
    assert r1.artifact_id != r2.artifact_id
    states = {s.artifact_id: s for s in catalog.find_by_workflow(wf_id)}
    assert len(states) == 2
    for s in states.values():
        assert str(getattr(s.status, "value", s.status)) == "committed"
        assert Path(s.storage_path).exists()

    # The earlier committed bytes are never overwritten.
    assert Path(r1.path).read_text(encoding="utf-8") == v1
    assert Path(r2.path).read_text(encoding="utf-8") == v2


