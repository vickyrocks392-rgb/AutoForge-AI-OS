"""
DEF-18L-01 regression: generated source must become an authoritative durable
artifact.

The P-1 gate left one Medium item open: "Generated source files are written to
the workspace filesystem but are not currently registered as durable
artifacts." The 18-L greenfield run demonstrated it empirically -- the M6 model
produced real ``src/models/*.py`` files, but the only thing that reached the
18-K catalog was the diff summary ``"Modified files: ..."``.

These tests pin the repair at the existing engineering-loop/artifact boundary
and, critically, pin that the repair reuses the ONE authoritative path
(ArtifactPipeline -> DurableArtifactCatalog -> PhysicalArtifactStore) rather
than introducing a second artifact store.
"""

