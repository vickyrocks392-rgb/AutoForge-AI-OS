# ── Simple event collector ──────────────────────────────────────────────────


class SimpleEventSink:
    """In-memory event collector for test verification."""

    def __init__(self) -> None:
        self.events: list[Any] = []

    def publish(self, event: Any) -> None:
        self.events.append(event)

    def clear(self) -> None:
        self.events.clear()

    def get_events_by_type(self, event_type: str) -> list[Any]:
        return [
            e for e in self.events
            if _event_type_name(e) == event_type
            or _event_type_value(e) == event_type
        ]

    def has_event_type(self, event_type: str) -> bool:
        return any(
            _event_type_name(e) == event_type or _event_type_value(e) == event_type
            for e in self.events
        )


def _event_type_name(event: Any) -> str:
    et = getattr(event, "event_type", None)
    if et is None:
        return ""
    return getattr(et, "name", str(et))


def _event_type_value(event: Any) -> str:
    et = getattr(event, "event_type", None)
    if et is None:
        return ""
    return getattr(et, "value", str(et))


# ── Deterministic AI provider ──────────────────────────────────────────────


class DeterministicStageAIProvider:
    """
    Deterministic AI provider that produces scripted outputs for E2E testing.

    Simulates the AI engineering provider protocol without requiring a real LLM.
    Always produces a syntactically valid Python file that the engineering loop
    can import, so verification commands that check the file's existence and
    importability pass.
    """

    def __init__(
        self,
        *,
        plans_generated: list[str] | None = None,
        implementations_generated: list[list[dict[str, Any]]] | None = None,
        diagnoses_performed: list[Any] | None = None,
        repairs_generated: list[list[dict[str, Any]]] | None = None,
        fail_on_attempt: int | None = None,
    ) -> None:
        self.plans_generated = plans_generated or []
        self.implementations_generated = implementations_generated or []
        self.diagnoses_performed = diagnoses_performed or []
        self.repairs_generated = repairs_generated or []
        self.fail_on_attempt = fail_on_attempt  # If set, generate code that causes test to fail

        self._impl_counter = 0
        self._diag_counter = 0
        self._repair_counter = 0

    async def generate_plan(self, context: Any) -> str:
        plan = f"Plan for {context.task_name} (attempt {context.attempt_number})"
        self.plans_generated.append(plan)
        return plan

    async def generate_implementation(
        self, context: Any, plan: str
    ) -> list[dict[str, Any]]:
        # Deterministic implementation: produce a simple Python file
        # Use a unique module name per stage to avoid collisions
        safe_task_id = context.task_id.replace("-", "_").replace(".", "_")
        impl = [
            {
                "path": f"{safe_task_id}_generated.py",
                "content": f'"""Auto-generated by DeterministicStageAIProvider for {context.task_name}."""\n\n'
                f"def solve():\n"
                f'    """Deterministic implementation for {context.task_name}."""\n'
                f"    return True\n",
            }
        ]
        self.implementations_generated.append(impl)
        return impl

    async def diagnose_failure(
        self, context: Any, failure_evidence: dict[str, Any]
    ) -> Any:
        from autoforge_execution.models import DiagnosisReport

        diagnosis = DiagnosisReport(
            root_cause="Deterministic test: simulated failure diagnosed",
            failure_mechanism=f"Simulated test failure on attempt {context.attempt_number}",
            affected_files=context.project_files,
            suggested_fix="Apply deterministic repair",
            confidence_score=1.0,
        )
        self.diagnoses_performed.append(diagnosis)
        return diagnosis

    async def generate_repair(
        self, context: Any, diagnosis: Any
    ) -> list[dict[str, Any]]:
        safe_task_id = context.task_id.replace("-", "_").replace(".", "_")
        repair = [
            {
                "path": f"{safe_task_id}_generated.py",
                "content": f'"""Repaired by DeterministicStageAIProvider."""\n\n'
                f"def solve():\n"
                f'    """Repaired implementation for {context.task_name}."""\n'
                f"    return True\n",
            }
        ]
        self.repairs_generated.append(repair)
        return repair


def default_verification_command(task_id: str) -> list[str]:
    """Return a real verification command that checks the generated file
    exists and is syntactically valid (importable) Python.

    This is a real, meaningful check - not a fake pass.
    """
    safe_task_id = task_id.replace("-", "_").replace(".", "_")
    return [
        sys.executable,
        "-c",
        (
            "import importlib.util, pathlib; "
            f"p = pathlib.Path('{safe_task_id}_generated.py'); "
            "assert p.exists(), f'Generated file {{p}} not found'; "
            f"spec = importlib.util.spec_from_file_location('mod_{safe_task_id}', p); "
            "assert spec is not None, 'Module spec is None'; "
            "mod = importlib.util.module_from_spec(spec); "
            "spec.loader.exec_module(mod); "
            "assert hasattr(mod, 'solve'), 'solve() function missing'; "
            "assert mod.solve() is True, 'solve() returned non-True'; "
            "print('VERIFIED', p.name)"
        ),
    ]
